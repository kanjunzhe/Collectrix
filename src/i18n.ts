const stored = (() => {
  try {
    return localStorage.getItem("collectrix.locale");
  } catch {
    return null;
  }
})();

export function resolveLocale(value: string | null | undefined): Locale {
  return value === "en" ? "en" : "zh";
}

locale.value = resolveLocale(stored);

export function setLocale(value: string | null | undefined) {
  locale.value = resolveLocale(value);
  document.documentElement.lang = locale.value === "zh" ? "zh-CN" : "en";
  document.title = "Collectrix";
  try {
    localStorage.setItem("collectrix.locale", locale.value);
  } catch {
    // ignore storage errors
  }
}

/** 用中文文案作为 key；缺失的英文翻译会回退到中文。 */
export function t(
  key: string,
  params?: Record<string, string | number>,
): string {
  let text = locale.value === "en" ? (en[key] ?? key) : key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

